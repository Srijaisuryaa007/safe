/**
 * locationValidator.ts
 * Rigorous validation and sanitization for GPS coordinates to eliminate fake/spoofed locations,
 * coordinate replay attacks, and out-of-bounds anomalies.
 */

export interface GpsValidationInput {
  latitude: number | null | undefined;
  longitude: number | null | undefined;
  accuracy?: number | null;
  speed?: number | null;
  timestamp?: number | string | null;
  mocked?: boolean | null;
}

export interface GpsValidationResult {
  isValid: boolean;
  sanitizedLat: number;
  sanitizedLng: number;
  reason?: string;
  isMocked: boolean;
}

// Track previous valid fix per user to detect impossible velocity/teleportation attacks
const lastValidFixMap = new Map<string, { lat: number; lng: number; timeMs: number }>();

function calculateHaversineMeters(lat1: number, lon1: number, lat2: number, lon2: number): number {
  const R = 6371e3;
  const phi1 = (lat1 * Math.PI) / 180;
  const phi2 = (lat2 * Math.PI) / 180;
  const deltaPhi = ((lat2 - lat1) * Math.PI) / 180;
  const deltaLambda = ((lon2 - lon1) * Math.PI) / 180;

  const a =
    Math.sin(deltaPhi / 2) * Math.sin(deltaPhi / 2) +
    Math.cos(phi1) * Math.cos(phi2) * Math.sin(deltaLambda / 2) * Math.sin(deltaLambda / 2);
  const c = 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1 - a));
  return R * c;
}

/**
 * Validate and sanitize GPS telemetry fix before local processing or remote transmission.
 */
export function validateAndSanitizeGpsFix(
  input: GpsValidationInput,
  userId?: string
): GpsValidationResult {
  const { latitude, longitude, accuracy, timestamp, mocked } = input;

  // 1. Hardware Mock GPS Provider Rejection
  if (mocked === true) {
    return {
      isValid: false,
      sanitizedLat: 0,
      sanitizedLng: 0,
      isMocked: true,
      reason: 'Rejected: Coordinate generated by mock location provider',
    };
  }

  // 2. Type & NaN Check
  if (
    typeof latitude !== 'number' ||
    typeof longitude !== 'number' ||
    isNaN(latitude) ||
    isNaN(longitude) ||
    !isFinite(latitude) ||
    !isFinite(longitude)
  ) {
    return {
      isValid: false,
      sanitizedLat: 0,
      sanitizedLng: 0,
      isMocked: false,
      reason: 'Rejected: Coordinates are not finite numbers',
    };
  }

  // 3. Coordinate Bounds Validation (WGS 84 Standard)
  if (latitude < -90 || latitude > 90 || longitude < -180 || longitude > 180) {
    return {
      isValid: false,
      sanitizedLat: 0,
      sanitizedLng: 0,
      isMocked: false,
      reason: 'Rejected: Coordinates out of valid geographic range [-90..90, -180..180]',
    };
  }

  // 4. Null Island / Defective GPS Chip Filter (0.0000, 0.0000)
  if (Math.abs(latitude) < 0.0001 && Math.abs(longitude) < 0.0001) {
    return {
      isValid: false,
      sanitizedLat: 0,
      sanitizedLng: 0,
      isMocked: false,
      reason: 'Rejected: Null Island coordinate (0.0, 0.0) generated by uncalibrated GPS chip',
    };
  }

  // 5. Accuracy Gate: Discard unusable fixes (> 200m radius error)
  if (typeof accuracy === 'number' && accuracy > 200) {
    return {
      isValid: false,
      sanitizedLat: 0,
      sanitizedLng: 0,
      isMocked: false,
      reason: `Rejected: Low accuracy GPS fix (${Math.round(accuracy)}m > 200m threshold)`,
    };
  }

  // 6. Timestamp Replay Attack & Staleness Gate
  const nowMs = Date.now();
  let fixTimeMs = nowMs;
  if (timestamp) {
    fixTimeMs = typeof timestamp === 'number' ? timestamp : new Date(timestamp).getTime();
    if (!isNaN(fixTimeMs)) {
      // Reject stale telemetry older than 15 minutes or future telemetry > 5 minutes in future
      const ageMs = nowMs - fixTimeMs;
      if (ageMs > 900000) {
        return {
          isValid: false,
          sanitizedLat: 0,
          sanitizedLng: 0,
          isMocked: false,
          reason: 'Rejected: Stale telemetry packet (>15 minutes old)',
        };
      }
      if (ageMs < -300000) {
        return {
          isValid: false,
          sanitizedLat: 0,
          sanitizedLng: 0,
          isMocked: false,
          reason: 'Rejected: Telemetry timestamp is in the future (>5 minutes)',
        };
      }
    }
  }

  // 7. Teleportation / Impossible Speed Anomaly Filter
  if (userId && lastValidFixMap.has(userId)) {
    const last = lastValidFixMap.get(userId)!;
    const deltaSec = Math.max(0.5, (fixTimeMs - last.timeMs) / 1000);
    const distanceM = calculateHaversineMeters(last.lat, last.lng, latitude, longitude);
    const speedKmh = (distanceM / deltaSec) * 3.6;

    // Speeds exceeding 900 km/h (commercial jet cruising velocity) represent spoofed jumps
    if (speedKmh > 900 && distanceM > 1000) {
      return {
        isValid: false,
        sanitizedLat: 0,
        sanitizedLng: 0,
        isMocked: false,
        reason: `Rejected: Teleportation anomaly detected (${Math.round(speedKmh)} km/h jump across ${Math.round(distanceM)}m)`,
      };
    }
  }

  // Sanitize to 6 decimal places (~0.1m precision)
  const sanitizedLat = parseFloat(latitude.toFixed(6));
  const sanitizedLng = parseFloat(longitude.toFixed(6));

  if (userId) {
    lastValidFixMap.set(userId, { lat: sanitizedLat, lng: sanitizedLng, timeMs: fixTimeMs });
  }

  return {
    isValid: true,
    sanitizedLat,
    sanitizedLng,
    isMocked: false,
  };
}
